  /* -----------------------------------------------------------
     安装补全：加载 language_tools（含 snippets），启用实时补全，
     注册 8 语言自定义 completer
     getLang: 回调，返回当前文件语言 id（python/java/...）
  ----------------------------------------------------------- */
  function install(editor, ace, getLang) {
    ace.config.loadModule('ace/ext/language_tools', function () {
        try {
          editor.setOptions({
            enableBasicAutocompletion: true,
            enableSnippets: true,
            enableLiveAutocompletion: true
          });
        } catch (e) { /* 选项设置失败不影响编辑器 */ }

        // 自定义 completer：根据当前语言返回对应补全项
        var customCompleter = {
          getCompletions: function (ed, session, pos, prefix, callback) {
            try {
              var lang = (typeof getLang === 'function') ? getLang() : null;
              var items = (lang && D[lang]) ? D[lang] : [];
              // 过滤：prefix 非空时只保留匹配项（Ace 会自动过滤，这里兜底）
              if (prefix && prefix.length > 0) {
                var p = prefix.toLowerCase();
                items = items.filter(function (it) {
                  return it.caption && it.caption.toLowerCase().indexOf(p) === 0;
                });
              }
              callback(null, items);
            } catch (e) {
              callback(null, []);
            }
          }
        };

        if (editor.completers) {
          // 去重后追加
          var exists = editor.completers.some(function (c) { return c === customCompleter; });
          if (!exists) editor.completers.push(customCompleter);
        } else {
          editor.completers = [customCompleter];
        }
    });
  }

  CL.BceCompleters = { install: install, DATA: D };
